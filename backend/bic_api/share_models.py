"""Allowlisted, plain-text parent summaries; never an archived answer sheet.

Aggregate scores and narrative are generated by the owner with the browser's
versioned rule engine. This schema is a privacy/shape boundary, not certification
of school marks or admission outcomes.
"""

import json
from typing import Annotated, Literal

from pydantic import AfterValidator, BaseModel, ConfigDict, Field, StrictInt, StrictStr, model_validator

from .models import bounded_text, utf16_length


MAX_SAFE_INTEGER = 9_007_199_254_740_991
MAX_CONTENT_UNITS = 24_000
MAX_SNAPSHOT_UNITS = 26_000


def plain_text(maximum, *, required=False):
    def validate(value):
        bounded_text(maximum, required=required)(value)
        try:
            value.encode('utf-8')
        except UnicodeError:
            raise ValueError('text must contain valid Unicode characters') from None
        return value
    return Annotated[StrictStr, AfterValidator(validate)]


def serialized_units(value):
    return utf16_length(json.dumps(value, ensure_ascii=False, separators=(',', ':'), allow_nan=False))


class PublicModel(BaseModel):
    model_config = ConfigDict(extra='forbid', strict=True, allow_inf_nan=False)


PositiveInteger = Annotated[StrictInt, Field(ge=1, le=MAX_SAFE_INTEGER)]
SubjectKey = Literal['english', 'maths', 'physics', 'chemistry']


class ShareSubject(PublicModel):
    key: SubjectKey
    name: plain_text(24, required=True)
    answered: Annotated[StrictInt, Field(ge=0, le=15)]
    total: Annotated[StrictInt, Field(ge=15, le=15)]
    pct: Annotated[StrictInt, Field(ge=0, le=100)] | None

    @model_validator(mode='after')
    def measured_percentage(self):
        if (self.answered < self.total and self.pct is not None
                or self.answered == self.total and self.pct is None):
            raise ValueError('only completed subjects have a measured percentage')
        return self


class ShareSections(PublicModel):
    summary: plain_text(4000, required=True)
    academic: plain_text(4000, required=True)
    plan: plain_text(4000, required=True)
    personality: plain_text(4000, required=True)


class ShareContent(PublicModel):
    status: Literal['draft', 'complete']
    direction: plain_text(120, required=True)
    personality: plain_text(120, required=True)
    subjects: list[ShareSubject] = Field(min_length=4, max_length=4)
    sections: ShareSections

    @model_validator(mode='after')
    def public_content_boundary(self):
        if {subject.key for subject in self.subjects} != {'english', 'maths', 'physics', 'chemistry'}:
            raise ValueError('exactly four unique academic subjects are required')
        if self.status == 'complete' and any(subject.answered < subject.total for subject in self.subjects):
            raise ValueError('a completed report cannot contain unfinished academic subjects')
        if serialized_units(self.model_dump(mode='json')) > MAX_CONTENT_UNITS:
            raise ValueError('public summary exceeds its serialized size limit')
        return self


class ShareReport(PublicModel):
    name: plain_text(24, required=True)
    grade: Literal['', '8', '9', '10', '11']
    year: plain_text(40)
    batchId: plain_text(100, required=True)
    date: plain_text(80, required=True)
    bankVersion: plain_text(100, required=True)
    catalogVersion: plain_text(100, required=True) | None
    revision: PositiveInteger


class ParentSnapshot(PublicModel):
    format: Literal['bic-parent-summary']
    version: Annotated[StrictInt, Field(ge=1, le=1)]
    shared_at: PositiveInteger
    expires_at: PositiveInteger
    report: ShareReport
    content: ShareContent

    @model_validator(mode='after')
    def public_snapshot_boundary(self):
        if self.expires_at <= self.shared_at:
            raise ValueError('expiry must follow creation')
        if serialized_units(self.model_dump(mode='json')) > MAX_SNAPSHOT_UNITS:
            raise ValueError('public snapshot exceeds its serialized size limit')
        return self


def build_parent_snapshot(record: dict, revision: int, shared_at: int,
                          expires_at: int, content: dict) -> dict:
    """Build one public snapshot from canonical saved metadata, never private state.

    Both anonymous shares and account-bound invitations use this allowlist.
    The caller supplies the authoritative database revision and lifecycle times;
    aggregate/narrative content still passes the same public schema boundary.
    """
    try:
        report = {
            'name': record['state']['info']['name'],
            'grade': record['state']['info']['grade'],
            'year': record['state']['info']['year'],
            'batchId': record['reportMeta']['batchId'],
            'date': record['reportMeta']['date'],
            'bankVersion': record['bankVersion'],
            'catalogVersion': record.get('catalogVersion'),
            'revision': revision,
        }
    except (KeyError, TypeError, AttributeError):
        raise ValueError('stored report metadata cannot produce a public snapshot') from None
    return ParentSnapshot.model_validate({
        'format': 'bic-parent-summary', 'version': 1,
        'shared_at': shared_at, 'expires_at': expires_at,
        'report': report, 'content': content,
    }).model_dump(mode='json')
